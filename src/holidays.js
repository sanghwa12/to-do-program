/** 그 날짜("YYYY-MM-DD")의 공휴일 이름. 공휴일이 아니면 undefined */
export function holidayName(dateStr) {
  return HOLIDAYS[dateStr];
}

/** 그 해의 공휴일 표가 들어 있는지 — 없는 해를 보면 달력에 안내를 띄움 */
export function hasHolidayData(year) {
  return Object.keys(HOLIDAYS).some((d) => d.startsWith(year + "-"));
}
